def run_live(args) -> int:
    sheet = load_cheatsheet(args.cheatsheet)
    if not sheet.get("players"):
        print(f"No cheat sheet found at {args.cheatsheet}.")
        print("Run the prep step first:")
        print(f"  python {os.path.basename(__file__)} --prep --league-id LEAGUE_ID")
        print("  (or --prep --from-csv rankings.csv)")
        print("\nContinuing with Sleeper's own ordering only — much weaker.\n")
        time.sleep(2)
    else:
        print(f"Cheat sheet: {len(sheet['players'])} players "
              f"(source: {sheet.get('source')}, built {sheet.get('generated_at')})")
    sheet_index = index_cheatsheet(sheet)

    league = None
    if args.league_id:
        league = get_league(args.league_id)
        drafts = get_drafts_for_league(args.league_id)
        if not drafts:
            print("No draft found for that league.", file=sys.stderr)
            return 1
        draft_id = drafts[0]["draft_id"]
    else:
        draft_id = args.draft_id

    draft = get_draft(draft_id)
    players = get_all_players(force_refresh=args.refresh_players)
    my_user = get_user(args.my_username)

    my_roster_id = None
    if args.league_id:
        rosters = get_rosters(args.league_id)
        my_roster = next(
            (
                r for r in rosters
                if r.get("owner_id") == my_user["user_id"]
                or my_user["user_id"] in (r.get("co_owners") or [])
            ),
            None,
        )
        my_roster_id = my_roster["roster_id"] if my_roster else None

    my_slot = my_slot_from_draft(draft, my_user["user_id"], my_roster_id)
    teams = (draft.get("settings") or {}).get("teams") or 0
    if my_slot:
        print(f"Drafting from slot {my_slot} of {teams}.")
    else:
        print("Draft order not assigned yet — Sleeper usually sets it just before the draft. "
              "Recommendations still work; the wrap math activates once your slot is known.")
    time.sleep(1.5)

    clear_cmd = "cls" if os.name == "nt" else "clear"

    while True:
        draft = get_draft(draft_id)
        picks = sorted(get_draft_picks(draft_id), key=lambda p: p.get("pick_no") or 0)
        next_pick_no = len(picks) + 1
        if my_slot is None:
            my_slot = my_slot_from_draft(draft, my_user["user_id"], my_roster_id)

        my_picks = my_upcoming_picks(draft, next_pick_no, my_slot) if my_slot else []
        drafted_ids = {p.get("player_id") for p in picks}

        my_own = [
            p for p in picks
            if (my_roster_id is not None and p.get("roster_id") == my_roster_id)
            or p.get("picked_by") == my_user["user_id"]
        ]
        my_positions = [
            pos for pos in
            ((players.get(p.get("player_id")) or {}).get("position") for p in my_own)
            if pos
        ]
        needs = compute_needs(roster_positions_for(draft, league), my_positions)
        runs = positional_run(picks, players)

        os.system(clear_cmd)
        print(f"=== {str(draft.get('status','?')).upper()} | {len(picks)} picks in | "
              f"on the clock: {describe_pick(draft, next_pick_no)} ===")
        if my_picks:
            away = my_picks[0] - next_pick_no
            you = "  <<< YOU ARE ON THE CLOCK" if away == 0 else f"  ({away} picks away)"
            print(f"Your next: {describe_pick(draft, my_picks[0])}{you}")
            if len(my_picks) > 1:
                print(f"Then:      {describe_pick(draft, my_picks[1])} "
                      f"({my_picks[1] - my_picks[0] - 1} picks in between)")

        roster_str = ", ".join(
            f"{(players.get(p.get('player_id')) or {}).get('full_name','?')}"
            f" ({(players.get(p.get('player_id')) or {}).get('position','?')})"
            for p in my_own
        )
        print(f"Your roster ({len(my_own)}): {roster_str or 'empty'}")
        print(f"Unfilled starters: {needs or 'none'}")
        if runs:
            print(f"Last 10 picks: {', '.join(f'{k} x{v}' for k, v in runs.most_common())}")
        print()

        board = build_board(players, drafted_ids, sheet_index)
        reco = recommend(board, needs, my_picks, next_pick_no, runs)
        render_recommendation(reco, needs, my_picks, draft)

        if args.once:
            return 0
        if draft.get("status") == "complete":
            print("Draft complete.")
            return 0
        time.sleep(args.poll)


def main() -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--prep", action="store_true",
                        help="Build the cheat sheet (run once, before the draft)")
    parser.add_argument("--from-csv", help="Build the cheat sheet from a rankings CSV instead")
    parser.add_argument("--from-sleeper", action="store_true",
                        help="Build the cheat sheet from Sleeper's own ordering (no API, instant)")
    parser.add_argument("--repair", action="store_true",
                        help="Rebuild the cheat sheet from a saved raw response (no API call)")
    parser.add_argument("--raw", help="Raw response file to repair from")
    parser.add_argument("--size", type=int, default=200, help="How many players to rank (default 200)")
    parser.add_argument("--batch", type=int, default=50,
                        help="Players per generation call (default 50)")
    parser.add_argument("--reuse-research", action="store_true",
                        help="Skip re-researching; reuse the saved brief")
    parser.add_argument("--league-id", help="Sleeper league ID")
    parser.add_argument("--draft-id", help="Sleeper draft ID directly (mock drafts)")
    parser.add_argument("--my-username", help="Your Sleeper username (required for live mode)")
    parser.add_argument("--cheatsheet", default=CHEATSHEET_PATH,
                        help=f"Cheat sheet path (default {CHEATSHEET_PATH})")
    parser.add_argument("--poll", type=int, default=5, help="Seconds between polls (default 5)")
    parser.add_argument("--once", action="store_true",
                        help="Print one recommendation and exit (for testing)")
    parser.add_argument("--refresh-players", action="store_true", help="Force player DB re-download")
    args = parser.parse_args()

    try:
        if args.repair:
            return run_repair(args)
        if args.from_sleeper:
            return run_prep_from_sleeper(args)
        if args.prep or args.from_csv:
            return run_prep(args)

        if not args.my_username:
            parser.error("--my-username is required for live mode")
        if not (args.league_id or args.draft_id):
            parser.error("one of --league-id or --draft-id is required for live mode")
        return run_live(args)

    except KeyboardInterrupt:
        print("\nStopped.")
        return 0
    except requests.exceptions.RequestException as e:
        print(f"\nNetwork/API error (Sleeper): {e}", file=sys.stderr)
        return 1
    except ValueError as e:
        print(f"\n{e}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
